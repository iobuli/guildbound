def _note(dur, f_of_t, amp_of_t, rng, harm=0.08):
    """One bird note: a pure whistle following f(t) (with a faint 2nd harmonic and breath)."""
    n = int(dur * SR)
    u = np.linspace(0, 1, n)
    f = f_of_t(u)
    ph = 2 * math.pi * np.cumsum(f) / SR
    x = np.sin(ph) + harm * np.sin(2 * ph + 0.7)
    x = x * amp_of_t(u) + bp(noise(dur, rng), 2500, 9000) * amp_of_t(u) * 0.015
    return x


def bird(rng):
    """A songbird somewhere in the trees: one of four song shapes (two-note whistle, trill, chirp run,
    warble) with natural pitch contours and vibrato, rolled off and given a little distance."""
    kind = int(rng.integers(0, 4))
    hump = lambda u: np.sin(np.pi * u) ** 0.8
    parts = []
    if kind == 0:  # "fee-bee": a high note, a lower one
        f1 = rng.uniform(3600, 4300)
        parts.append((_note(0.22, lambda u: f1 * (1 + 0.012 * np.sin(2 * math.pi * 6 * u)), hump, rng), 0.0, 0.0))
        f2 = f1 * rng.uniform(0.78, 0.86)
        parts.append((_note(0.26, lambda u: f2 * (1 - 0.03 * u), hump, rng), 0.29, -2.0))
    elif kind == 1:  # trill
        f0 = rng.uniform(4200, 5200)
        dur = rng.uniform(0.45, 0.65)
        rate = rng.uniform(16, 22)
        parts.append((_note(dur, lambda u: f0 * (1 + 0.06 * np.sin(2 * math.pi * rate * dur * u) - 0.05 * u),
                            lambda u: hump(u) * (0.5 + 0.5 * np.sin(2 * math.pi * rate * dur * u) ** 2), rng), 0.0, 0.0))
    elif kind == 2:  # a run of rising chirps
        at = 0.0
        for k in range(int(rng.integers(3, 6))):
            d = rng.uniform(0.045, 0.075)
            f0 = rng.uniform(2600, 3400)
            f1 = f0 * rng.uniform(1.35, 1.6)
            parts.append((_note(d, lambda u, f0=f0, f1=f1: f0 + (f1 - f0) * u ** 1.5, hump, rng), at, -k * 0.8))
            at += d + rng.uniform(0.04, 0.07)
    else:  # warble
        f0 = rng.uniform(2900, 3500)
        dur = rng.uniform(0.35, 0.5)
        parts.append((_note(dur, lambda u: f0 * (1 + 0.14 * np.sin(2 * math.pi * 11 * dur * u + 1.3 * np.sin(2 * math.pi * 3 * dur * u))),
                            hump, rng, 0.12), 0.0, 0.0))
    x = lp(lay(*parts), 8500)
    return verb(x, 0.9, 0.35, 5000, pre=0.025, seed=int(rng.integers(1 << 30)))


def ambience_wind(rng, dur=16.0):
    """A seamless stereo wind bed: pink and brown noise in three bands whose levels breathe in gusts,
    a faint whistle on the strongest gusts, and leaves rustling (grains of the cloth and paper
    recordings) as each gust passes. Every filter and modulation is periodic over the loop."""
    n = int(dur * SR)
    t = np.arange(n) / SR

    def lfo(seed_shift):
        r = np.random.default_rng(int(rng.integers(1 << 30)) + seed_shift)
        g = sum(r.uniform(0.3, 1.0) / k * np.sin(2 * math.pi * k * t / dur + r.uniform(0, 6.28)) for k in (1, 2, 3, 5))
        return np.clip(0.5 + 0.5 * g / 1.6, 0.0, 1.0)

    def band(x, lo, hi):
        spec = np.fft.rfft(x)
        f = np.fft.rfftfreq(n, 1 / SR)
        spec *= np.exp(-0.5 * (np.log2((f + 1) / math.sqrt(lo * hi)) / (math.log2(hi / lo) / 2)) ** 2)
        spec *= f ** 4 / (f ** 4 + 30.0 ** 4)  # nothing below hearing: no slow wander of the speaker cone
        return np.fft.irfft(spec, n)

    gust = lfo(1)
    chans = []
    for c in range(2):
        r = np.random.default_rng(int(rng.integers(1 << 30)) + c)
        g = np.roll(gust, int(c * 0.35 * SR))  # the gust reaches each ear a little apart
        low = band(pink(n, r, 1.0), 40, 220) * (0.3 + 0.7 * g)
        mid = band(pink(n, r, 0.5), 250, 900) * (0.1 + 0.9 * g ** 1.5)
        high = band(pink(n, r, 0.5), 1600, 2600) * np.clip(g - 0.6, 0, 1) ** 2 * 1.6
        leaves = np.zeros(n)
        for src in ("cloth4", "bookFlip2", "bookFlip3", "cloth2"):
            s = grains(rec(src), dur, 90, r, (0.01, 0.05), (0.7, 1.3), (0.2, 1.0),
                       at=lambda rr: rr.uniform(0, dur))
            s = s[:n] + np.pad(s[n:], (0, max(0, 2 * n - len(s))))[:n]  # wrap the overhang: still seamless
            leaves += s
        leaves = hp(leaves, 1800) * np.clip(g - 0.35, 0, 1) ** 1.5
        x = unit(low) * 1.0 + unit(mid) * 0.55 + unit(high) * 0.05 + unit(leaves) * 0.06
        chans.append(x)
    return np.stack(chans, axis=1)


