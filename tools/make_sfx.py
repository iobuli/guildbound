"""Builds the game's combat, magic, monster and ambience sounds into assets/audio/synth/*.wav.

Recorded first. Every cue is layered from the real CC0 foley already in assets/audio (Kenney "Impact
Sounds" and "RPG Audio": body punches, soft thuds, light metal, plate, cloth, leather, paper, coins,
footsteps) and processed the way a sound designer would treat a library:

  varispeed     tape-style pitch + time (a cloth flap slowed down becomes a great-sword's whoomp)
  filtering     high/low/band-pass, shelves, and a gliding band-pass for pass-by whooshes
  transients    an attack/sustain shaper so blows crack and swishes stay soft
  reversing     swells and sucks that lead into a release
  granular      scattering tiny grains (paper -> fire crackle, coins -> ice shards, metal -> sparks)
  reverb        short convolution tails so nothing ends dry and cheap

Synthesis is only a sweetener (sub thumps under heavy hits, tonal shimmer for magic, the swept air of
a whoosh) - except for the wind bed and the birds, which no recording here covers. Each cue gets a few
variants (different sources, rates and seeds) so repeats never sound identical; game/sfx.gd picks one
at random. Every file is loudness-matched to TARGET_LUFS (an approximate ITU-R BS.1770 K-weighted
loudness over the loudest stretch of the sound, at most 400 ms) and peak-limited to CEILING_DB, and
assets/audio/synth/levels.json records what each file measured. assets/audio/CREDITS.txt lists the
recordings each cue is built from (regenerated by this script).

Needs numpy, scipy and soundfile (pip install numpy scipy soundfile); without soundfile it decodes
the .ogg files with ffmpeg. Run from anywhere:  python tools/make_sfx.py
"""
import json
import math
import os
import subprocess
import wave
import zlib
from fractions import Fraction

import numpy as np
from scipy import signal
from scipy.ndimage import convolve1d, minimum_filter1d

SR = 44100
HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.normpath(os.path.join(HERE, "..", "assets", "audio"))
OUT = os.path.join(SRC, "synth")
TARGET_LUFS = -16.0
CEILING_DB = -1.0
WIND_LUFS = -14.0          # the wind bed sits under everything (ambience.gd plays it at -14 dB on the Ambience bus)

_rec_cache = {}
_used = {}                 # cue -> set of recordings it was built from (for CREDITS.txt)
_cue = [""]


# ---- recordings ----------------------------------------------------------------------------------

def _decode(path):
    try:
        import soundfile
        x, sr = soundfile.read(path, dtype="float64", always_2d=True)
        return x.mean(axis=1), sr
    except ImportError:
        raw = subprocess.run(["ffmpeg", "-v", "quiet", "-i", path, "-f", "f32le", "-ac", "1", "-ar", str(SR), "-"],
                             capture_output=True, check=True).stdout
        return np.frombuffer(raw, dtype="<f4").astype(np.float64), SR


def rec(name):
    """A recording from assets/audio as mono float at SR, unit peak, starting just before its onset."""
    if name not in _rec_cache:
        x, sr = _decode(os.path.join(SRC, name + ".ogg"))
        if sr != SR:
            fr = Fraction(SR, sr)
            x = signal.resample_poly(x, fr.numerator, fr.denominator)
        x = x - np.mean(x)
        pk = np.max(np.abs(x)) + 1e-12
        on = int(np.argmax(np.abs(x) > pk * 0.25))  # the main event (some takes have a little handling noise first)
        x = x[max(0, on - int(0.005 * SR)):] / pk
        _rec_cache[name] = fade(x, 0.002, 0.005)
    _used.setdefault(_cue[0], set()).add(name)
    return _rec_cache[name].copy()


def pick(rng, *names):
    return rec(names[int(rng.integers(0, len(names)))])


# ---- building blocks -----------------------------------------------------------------------------

def db(g):
    return 10.0 ** (g / 20.0)


def secs(x):
    return len(x) / SR


def vs(x, r):
    """Varispeed: r > 1 plays faster (higher and shorter), r < 1 slower (lower and longer)."""
    if abs(r - 1.0) < 1e-3:
        return x.copy()
    fr = Fraction(1.0 / r).limit_denominator(300)
    return signal.resample_poly(x, fr.numerator, fr.denominator)


def _sos(kind, f, order):
    return signal.butter(order, f, btype=kind, fs=SR, output="sos")


def hp(x, f, order=2):
    return signal.sosfilt(_sos("highpass", f, order), x)


def lp(x, f, order=2):
    return signal.sosfilt(_sos("lowpass", min(f, SR * 0.45), order), x)


def bp(x, lo, hi, order=2):
    return signal.sosfilt(_sos("bandpass", [lo, min(hi, SR * 0.45)], order), x)


def biquad(x, kind, f, q=0.707, gain_db=0.0):
    """RBJ cookbook biquads: 'peak', 'highshelf', 'lowshelf', 'highpass'."""
    a_ = 10 ** (gain_db / 40.0)
    w = 2 * math.pi * f / SR
    cw, sw = math.cos(w), math.sin(w)
    al = sw / (2 * q)
    if kind == "peak":
        b = [1 + al * a_, -2 * cw, 1 - al * a_]
        a = [1 + al / a_, -2 * cw, 1 - al / a_]
    elif kind == "highshelf":
        s = 2 * math.sqrt(a_) * al
        b = [a_ * ((a_ + 1) + (a_ - 1) * cw + s), -2 * a_ * ((a_ - 1) + (a_ + 1) * cw), a_ * ((a_ + 1) + (a_ - 1) * cw - s)]
        a = [(a_ + 1) - (a_ - 1) * cw + s, 2 * ((a_ - 1) - (a_ + 1) * cw), (a_ + 1) - (a_ - 1) * cw - s]
    elif kind == "lowshelf":
        s = 2 * math.sqrt(a_) * al
        b = [a_ * ((a_ + 1) - (a_ - 1) * cw + s), 2 * a_ * ((a_ - 1) - (a_ + 1) * cw), a_ * ((a_ + 1) - (a_ - 1) * cw - s)]
        a = [(a_ + 1) + (a_ - 1) * cw + s, -2 * ((a_ - 1) + (a_ + 1) * cw), (a_ + 1) + (a_ - 1) * cw - s]
    else:  # highpass
        b = [(1 + cw) / 2, -(1 + cw), (1 + cw) / 2]
        a = [1 + al, -2 * cw, 1 - al]
    return signal.lfilter(np.array(b) / a[0], np.array(a) / a[0], x, axis=0)


def glide(x, pts, width=0.6, floor=0.02):
    """Band-pass whose centre glides through pts [(fraction of the sound, Hz), ...] (log-interpolated):
    the pass-by of a blade or a fist through the air. width is the band's sigma in octaves."""
    n = len(x)
    nper = 512
    f, t, z = signal.stft(x, SR, nperseg=nper, noverlap=nper * 3 // 4)
    frac = np.clip(t / max(secs(x), 1e-6), 0, 1)
    c = np.exp(np.interp(frac, [p[0] for p in pts], [math.log(p[1]) for p in pts]))
    oct_ = np.log2((f[:, None] + 1.0) / c[None, :])
    z *= floor + (1 - floor) * np.exp(-0.5 * (oct_ / width) ** 2)
    _, y = signal.istft(z, SR, nperseg=nper, noverlap=nper * 3 // 4)
    return np.pad(y, (0, max(0, n - len(y))))[:n]


def noise(dur, rng):
    return rng.standard_normal(int(SR * dur))


def pink(n, rng, slope=0.5):
    """1/f^(2*slope) noise shaped in the frequency domain (periodic over its length: loops cleanly)."""
    spec = np.fft.rfft(rng.standard_normal(n))
    f = np.fft.rfftfreq(n, 1 / SR)
    f[0] = f[1]
    y = np.fft.irfft(spec / f ** slope, n)
    return y / (np.std(y) + 1e-12)


def env_ad(n, attack, decay_power=2.0):
    t = np.linspace(0, 1, n)
    a = np.clip(t * (n / SR) / max(attack, 1e-4), 0, 1)
    return a * (1 - t) ** decay_power


def passby(n, peak=0.6, rise=2.0, fall=1.6):
    """Asymmetric whoosh envelope: swells to `peak` (fraction of the sound), then drops away."""
    t = np.linspace(0, 1, n)
    up = np.clip(t / peak, 0, 1) ** rise
    down = np.clip((1 - t) / (1 - peak), 0, 1) ** fall
    return np.where(t < peak, up, down)


def fade(x, fin=0.0015, fout=0.012):
    x = x.copy()
    a = min(len(x), int(fin * SR))
    b = min(len(x), int(fout * SR))
    if a > 1:
        x[:a] *= np.linspace(0, 1, a)
    if b > 1:
        x[-b:] *= np.linspace(1, 0, b) ** 2
    return x


def cut(x, dur, fout=0.03):
    return fade(x[: int(dur * SR)], 0.0, fout)


def unit(x):
    return x / (np.max(np.abs(x)) + 1e-12)


def lay(*parts):
    """Mix layers: each part is (signal, at_seconds, gain_db) or just a signal."""
    items = [(p, 0.0, 0.0) if isinstance(p, np.ndarray) else (p[0], p[1], p[2] if len(p) > 2 else 0.0) for p in parts]
    n = max(int(at * SR) + len(s) for s, at, _ in items)
    out = np.zeros(n)
    for s, at, g in items:
        i = int(at * SR)
        out[i:i + len(s)] += fade(s, 0.0008, 0.006) * db(g)  # no layer may start or stop with a click
    return out


def punch(x, attack_db=4.0, sustain_db=0.0):
    """Transient shaper: lift (or tame) the attack and the body independently of level."""
    a = np.abs(x)

    def follow(tau):
        k = math.exp(-1.0 / (tau * SR))
        return signal.lfilter([1 - k], [1, -k], a)

    fast, slow = follow(0.0007), follow(0.02)
    tr = np.clip((fast - slow) / (fast + 1e-9), 0, 1)
    su = np.clip((slow - fast) / (slow + 1e-9), 0, 1)
    g = attack_db * tr + sustain_db * su
    k = math.exp(-1.0 / (0.0015 * SR))
    g = signal.lfilter([1 - k], [1, -k], g)
    return x * db(g)


def sat(x, drive=2.0):
    """Soft saturation (weight and glue), level-matched to the input peak."""
    pk = np.max(np.abs(x)) + 1e-12
    return np.tanh(x / pk * drive) / math.tanh(drive) * pk


def verb(x, decay=0.6, wet=0.2, damp=5000.0, pre=0.012, seed=1):
    """Convolution reverb with a synthetic outdoor/stone-room response (early taps + a darkening tail)."""
    rng = np.random.default_rng(seed)
    n = int(SR * decay * 1.1)
    t = np.arange(n) / SR
    tail = lp(rng.standard_normal(n), damp) * np.exp(-6.9 * t / decay) + 0.5 * hp(rng.standard_normal(n), 2500) * np.exp(-6.9 * t / (decay * 0.4))
    tail[: int(0.005 * SR)] *= np.linspace(0, 1, int(0.005 * SR))
    ir = np.zeros(int(pre * SR) + n)
    for ms, g in ((3.1, 0.5), (7.7, 0.35), (11.3, 0.3), (17.9, 0.22), (23.0, 0.15)):
        ir[int(ms / 1000 * SR)] += g * (1 if rng.random() < 0.5 else -1)
    ir[int(pre * SR):] += tail * 0.06
    ir /= np.sqrt(np.sum(ir ** 2))
    y = signal.fftconvolve(x, ir)
    return np.pad(x, (0, len(y) - len(x))) + wet * y


def grains(src, dur, count, rng, glen=(0.004, 0.03), rate=(0.8, 1.25), gain=(0.3, 1.0), shape=None, at=None):
    """Granular scatter: `count` short windowed grains of `src` (taken from its loud parts) spread over
    `dur`, their density/level following shape(t in 0..1) and their placement at(rng) if given."""
    out = np.zeros(int(SR * dur) + int(0.1 * SR))
    lvl = np.convolve(np.abs(src), np.ones(64) / 64, mode="same")
    loud = np.where(lvl > 0.08 * lvl.max())[0]
    for _ in range(count):
        pos = at(rng) if at is not None else rng.uniform(0, dur)
        amp = rng.uniform(*gain) * (shape(pos / dur) if shape is not None else 1.0)
        if amp < 0.01:
            continue
        g = max(16, int(rng.uniform(*glen) * SR))
        r = rng.uniform(*rate)
        need = int(g * r) + 4
        s0 = int(loud[rng.integers(0, len(loud))]) if len(loud) else 0
        s0 = min(s0, max(0, len(src) - need))
        seg = vs(src[s0:s0 + need], r)[:g]
        seg = seg * np.hanning(len(seg))
        i = int(pos * SR)
        out[i:i + len(seg)] += seg * amp
    return out


def ring(dur, freqs, decays, rng, amps=None, detune=0.0):
    """Sweetener: decaying partials (metal, glass, bells)."""
    t = np.arange(int(SR * dur)) / SR
    out = np.zeros_like(t)
    for k, (f, d) in enumerate(zip(freqs, decays)):
        ff = f * (1 + rng.uniform(-detune, detune))
        # each partial is a slightly detuned pair: it beats and shimmers like real metal, not a test tone
        pair = np.sin(2 * math.pi * ff * t + rng.uniform(0, 6.28)) + 0.6 * np.sin(2 * math.pi * ff * 1.0035 * t + rng.uniform(0, 6.28))
        out += (amps[k] if amps else 1.0) * pair * np.exp(-t / d)
    return fade(out, 0.001, dur * 0.25)


def thump(dur, f0, f1, rng=None):
    """Sweetener: a sub-bass drop under a heavy impact."""
    t = np.arange(int(SR * dur)) / SR
    f = f1 + (f0 - f1) * np.exp(-t / (dur * 0.25))
    return fade(np.sin(2 * math.pi * np.cumsum(f) / SR) * np.exp(-t / (dur * 0.35)), 0.002, dur * 0.3)


def chirp(dur, f0, f1, curve=1.0):
    t = np.linspace(0, 1, int(SR * dur))
    f = f0 + (f1 - f0) * t ** curve
    return np.sin(2 * math.pi * np.cumsum(f) / SR)


def endtrim(x, floor_db=-54.0):
    """Drop the silent tail (below floor_db under the peak) with a short fade."""
    lvl = np.convolve(np.abs(x), np.ones(256) / 256, mode="same")
    live = np.where(lvl > np.max(lvl) * db(floor_db))[0]
    end = min(len(x), (live[-1] + int(0.02 * SR)) if len(live) else len(x))
    return fade(x[:end], 0.0, 0.02)


# ---- loudness and mastering ----------------------------------------------------------------------

def kweight(x):
    """BS.1770 K-weighting (high shelf +4 dB around 1.7 kHz, then the RLB high-pass ~38 Hz) at SR."""
    return biquad(biquad(x, "highshelf", 1681.97, 0.7072, 3.9998), "highpass", 38.135, 0.5003)


def loudness(x):
    """Approximate LUFS of a short sound: K-weighted mean square over its loudest window (400 ms, or
    the sound's active length when shorter, at least 100 ms). Stereo sums the channels' powers."""
    chans = [x] if x.ndim == 1 else [x[:, c] for c in range(x.shape[1])]
    p = sum(kweight(c) ** 2 for c in chans)
    lvl = np.convolve(np.sqrt(p), np.ones(256) / 256, mode="same")
    live = np.where(lvl > lvl.max() * db(-30))[0]
    active = (live[-1] - live[0]) / SR if len(live) else secs(p)
    w = max(16, int(SR * min(0.4, max(0.1, active))))
    if len(p) < w:
        p = np.pad(p, (0, w - len(p)))
    c = np.cumsum(np.concatenate([[0.0], p]))
    ms = (c[w:] - c[:-w]) / w
    return -0.691 + 10 * math.log10(ms.max() + 1e-12)


def limit(x, ceiling_db=CEILING_DB, look=0.0015):
    """Look-ahead peak limiter: the gain is a smoothed minimum of what each sample needs, so nothing
    passes the ceiling and no single-sample clicks are introduced."""
    c = db(ceiling_db)
    a = np.abs(x) if x.ndim == 1 else np.max(np.abs(x), axis=1)
    g = np.minimum(1.0, c / np.maximum(a, 1e-9))
    w = 2 * int(look * SR) + 1
    g = minimum_filter1d(g, w, mode="nearest")
    k = np.hanning(w + 2)[1:-1]
    g = convolve1d(g, k / k.sum(), mode="nearest")  # edge-held: no dip at the ends (the wind loop stays seamless)
    y = x * (g if x.ndim == 1 else g[:, None])
    pk = np.max(np.abs(y))
    return y * (c / pk) if pk > c else y


def master(x, target=TARGET_LUFS, max_gr_db=4.0):
    """DC out, silent tail off, loudness to target, peaks to the ceiling (at most max_gr_db of limiting:
    a sound whose transient would need more stays a little under target rather than be squashed)."""
    x = x - np.mean(x, axis=0)
    if x.ndim == 1:
        x = endtrim(x)
    gr = 0.0
    for _ in range(4):
        g = target - loudness(x)
        over = 20 * math.log10(np.max(np.abs(x)) * db(g) + 1e-12) - CEILING_DB
        if over > max_gr_db:
            g -= over - max_gr_db
        gr = max(gr, over, 0.0)
        x = limit(x * db(g))
        if abs(loudness(x) - target) < 0.2:
            break
    return x, min(gr, max_gr_db)


def save(name, x, target=TARGET_LUFS):
    os.makedirs(OUT, exist_ok=True)
    y, gr = master(x, target)
    data = np.clip(np.round(y * 32767), -32768, 32767).astype("<i2")
    with wave.open(os.path.join(OUT, name + ".wav"), "wb") as w:
        w.setnchannels(1 if y.ndim == 1 else y.shape[1])
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes(data.tobytes())
    return {"lufs": round(loudness(y), 2), "peak_db": round(20 * math.log10(np.max(np.abs(data)) / 32767 + 1e-12), 2),
            "seconds": round(len(y) / SR, 4), "limited_db": round(gr, 1)}


# ---- swings ----------------------------------------------------------------------------------------

CLOTH = ("cloth1", "cloth2", "cloth3", "cloth4")


def cloth_burst(rng, dur, rate):
    """The meatiest stretch of a cloth recording, varispeeded: the body of a whoosh."""
    x = vs(pick(rng, *CLOTH), rate)
    lvl = np.convolve(np.abs(x), np.ones(1024) / 1024, mode="same")
    n = int(dur * SR)
    if len(x) <= n:
        return np.pad(x, (0, n - len(x)))
    i = int(np.argmax(lvl[: len(x) - n // 2]))
    s = max(0, min(len(x) - n, i - n // 2))
    return x[s:s + n]


def swish(rng, dur, pts, width, rate, cloth_db=0.0, air_db=0.0, peak=0.6, steel_db=None):
    """A swung blade / fist / leg: recorded cloth movement (sped up or slowed) shaped by a pass-by
    envelope, plus a band of air gliding past (sweetener) and, for blades, a breath of steel."""
    n = int(dur * SR)
    e = passby(n, peak * rng.uniform(0.9, 1.1))
    c = cloth_burst(rng, dur, rate * rng.uniform(0.93, 1.07))
    body = glide(hp(c, 250), [(p, f * rng.uniform(0.9, 1.1)) for p, f in pts], width * 1.6, 0.15) * e
    air = glide(pink(n, rng, 0.35), [(p, f * rng.uniform(0.9, 1.1)) for p, f in pts], width) * e
    parts = [(unit(body), 0.0, cloth_db), (unit(air), 0.0, air_db - 4.0)]
    if steel_db is not None:
        st = pick(rng, "impactMetal_light_000", "impactMetal_light_001", "impactMetal_light_002")
        st = hp(vs(st, rng.uniform(1.25, 1.5)), 2500)[: n // 2]
        st = unit(st[::-1] * passby(len(st), 0.85, 2.5, 6.0))  # reversed: the ring swells into the cut
        parts.append((st, peak * dur * 0.55, steel_db))
    return verb(lay(*parts), 0.35, 0.12, 6000, seed=int(rng.integers(1 << 30)))


# ---- impacts ---------------------------------------------------------------------------------------

PUNCH_M = tuple("impactPunch_medium_%03d" % i for i in range(5))
PUNCH_H = tuple("impactPunch_heavy_%03d" % i for i in range(5))
SOFT_H = tuple("impactSoft_heavy_%03d" % i for i in range(5))
SOFT_M = tuple("impactSoft_medium_%03d" % i for i in range(3))
METAL = tuple("impactMetal_light_%03d" % i for i in range(3))
PLATE = tuple("impactPlate_light_%03d" % i for i in range(3))
PAPER = ("bookFlip1", "bookFlip2", "bookFlip3")
COINS = ("handleCoins", "handleCoins2")
LEATHER = ("handleSmallLeather", "handleSmallLeather2")
TINY_METAL = ("beltHandle1", "beltHandle2", "metalLatch", "metalClick")


def hit_blade(rng):
    """An edge biting into a body: a recorded flesh smack, the steel's bite on top, a slice of air and
    a little wet tear; a soft thud underneath for weight."""
    flesh = vs(pick(rng, *PUNCH_M), rng.uniform(0.95, 1.12))
    bite = cut(hp(vs(pick(rng, *METAL), rng.uniform(1.1, 1.35)), 2200), 0.16)
    slice_ = bp(noise(0.05, rng), 3000, 9000) * env_ad(int(0.05 * SR), 0.001, 3)
    tear = cut(hp(vs(pick(rng, *LEATHER), rng.uniform(1.3, 1.7)), 900), 0.12)
    weight = lp(vs(pick(rng, *SOFT_M), rng.uniform(0.9, 1.1)), 400)
    x = lay((flesh, 0.004, 0.0), (bite, 0.0, -9.0), (slice_, 0.0, -10.0), (tear, 0.012, -13.0), (weight, 0.002, -4.0))
    return verb(punch(sat(x, 1.6), 5.0, -1.0), 0.45, 0.14, 5000, seed=int(rng.integers(1 << 30)))


def clang(rng):
    """Steel meets steel (a blade on a guard): recorded plate and metal hits layered and retuned, a
    sparkle of tiny metal grains, a faint modal ring to carry the tail, a stone-room reverb."""
    r = rng.uniform(0.88, 1.12)
    plate = vs(pick(rng, *PLATE), r * 1.1)
    hit = vs(pick(rng, *METAL), r)
    body = lp(vs(pick(rng, *SOFT_M), 1.2), 600)
    sparks = hp(grains(rec(TINY_METAL[int(rng.integers(0, 4))]), 0.09, 14, rng, (0.002, 0.008), (1.2, 2.0),
                       shape=lambda u: (1 - u) ** 2), 4000)
    base = rng.uniform(1150, 1500)
    tail = ring(0.9, [base, base * 2.76, base * 5.4], [0.32, 0.18, 0.09], rng, [1.0, 0.6, 0.3], 0.01)
    x = lay((hit, 0.0, 0.0), (plate, 0.0, -2.0), (body, 0.0, -9.0), (sparks, 0.003, -10.0), (tail, 0.0, -21.0))
    return verb(punch(x, 4.0), 0.9, 0.2, 7000, seed=int(rng.integers(1 << 30)))


def parry(rng):
    """A clean deflection: a bright high 'ting' (light metal sped up), the plate's shimmer an octave
    above, a crystalline ring that hangs, sparks, and a longer reverb - the sweet spot made audible."""
    hit = vs(pick(rng, *METAL), rng.uniform(1.15, 1.3))
    plate = hp(vs(pick(rng, *PLATE), rng.uniform(1.8, 2.1)), 600)
    base = rng.uniform(2300, 2600)
    shine = ring(1.2, [base, base * 1.5, base * 2.24, base * 3.01], [0.5, 0.35, 0.22, 0.12], rng, [1.0, 0.5, 0.35, 0.2], 0.004)
