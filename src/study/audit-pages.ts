// Reproducible audit of the user's two engine pages (data embedded in the HTML, extracted to kev-brain/sources/pages/*.data.json):
// do the candles match the market data, what does each page's filter actually read, and how does its touch count work.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { openMarket } from '../core/market-io.js';
import { BRAIN, log } from '../brain/brain.js';

const H = 3_600_000;
const ts = (s: string) => Date.parse(s.replace(' ', 'T') + ':00Z');
const pct = (a: number, b: number) => `${a} of ${b}`;

export function auditPages(): string {
  const sol = openMarket('SOLUSDT').h1, byT = new Map(sol.map((b) => [b.t, b]));
  const L: string[] = ['# Audit of the user\'s engine pages', '', `Regenerated by \`kev audit-pages\` on ${new Date().toISOString().slice(0, 10)} from the data embedded in the pages (sources/pages/*.data.json) and Binance SOLUSDT H1.`, ''];
  // ---- Trade Check ----
  const tcPath = `${BRAIN}sources/pages/SOL_Trade_Check.data.json`;
  if (existsSync(tcPath)) {
    const D = JSON.parse(readFileSync(tcPath, 'utf8'));
    const rows = D.trades.map((t: any) => { const fb = t.c[t.entry_i], long = t.side === 'long'; return { kind: t.kind, win: t.win, R: t.R, ct: long ? fb[4] < t.level : fb[4] > t.level, touched: fb[3] <= t.level && t.level <= fb[2] }; });
    const g = (k: string, ct?: boolean) => rows.filter((r: any) => r.kind === k && (ct === undefined || r.ct === ct));
    const m = (xs: any[]) => (xs.length ? (xs.reduce((a, r) => a + r.R, 0) / xs.length).toFixed(2) : 'n/a');
    let match = 0, tot = 0; const byYear = new Map<string, [number, number]>();
    for (const t of D.trades) for (const r of t.c) { const b = byT.get(ts(r[0])); if (!b) continue; tot++; const ok = Math.max(Math.abs(b.o - r[1]), Math.abs(b.h - r[2]), Math.abs(b.l - r[3]), Math.abs(b.c - r[4])) <= 0.0101; if (ok) match++; const y = r[0].slice(0, 4), v = byYear.get(y) ?? [0, 0]; v[0] += ok ? 1 : 0; v[1]++; byYear.set(y, v); }
    L.push('## SOL Trade Check (43 sample trades)', '',
      `- Kept by the page: ${g('taken').length}; the fill bar closed back through the level on ${g('taken', true).length} of them. Rejected: ${g('rejected').length}; closed through on ${g('rejected', true).length}.`,
      `  The keep/reject rule is therefore exactly "the fill bar did not close through the level", which a resting limit order cannot know when it fills.`,
      `- Mean R: kept ${m(g('taken'))} (win ${(100 * g('taken').filter((r: any) => r.win).length / Math.max(1, g('taken').length)).toFixed(0)}%), rejected ${m(g('rejected'))}.`,
      `- The level traded inside every fill bar: ${pct(rows.filter((r: any) => r.touched).length, rows.length)}.`,
      `- Candles match Binance within rounding on ${pct(match, tot)} bars. By year: ${[...byYear].map(([y, [a, b]]) => `${y} ${(100 * a / b).toFixed(0)}%`).join(', ')}. From 2023-03 the page uses a different feed.`, '');
  }
  // ---- One Hour At A Time ----
  const ohPath = `${BRAIN}sources/pages/One_Hour_At_A_Time.data.json`;
  if (existsSync(ohPath)) {
    const D = JSON.parse(readFileSync(ohPath, 'utf8')), F: any[] = D.frames;
    const mism = F.filter((f) => { const b = byT.get(ts(f.ts)); return !b || Math.max(Math.abs(b.o - f.o), Math.abs(b.h - f.h), Math.abs(b.l - f.l), Math.abs(b.c - f.c)) > 0.0051; }).length;
    const dec = F.flatMap((f) => (f.retest ?? []).filter((r: any) => r.T1 !== undefined).map((r: any) => ({ ...r, f: f.f })));
    const exc = (from: number, to: number, r: any, atr: number) => { let m = 0; for (let k = from; k < to; k++) m = Math.max(m, (r.side === 'long' ? F[k].h - r.p : r.p - F[k].l) / atr); return m; };
    let withBar = 0, priorOnly = 0, closedThrough = 0;
    for (const r of dec) {
      const atr = F[r.f].atr;
      if (Math.abs(exc(r.b + 1, r.f + 1, r, atr) - r.far) < 0.006) withBar++;
      if (Math.abs(exc(r.b + 1, r.f, r, atr) - r.far) < 0.006) priorOnly++;
      const fb = F[r.f]; if (r.side === 'long' ? fb.c < r.p : fb.c > r.p) closedThrough++;
    }
    // touch rule: 3-bar swing points of the level's kind within 0.1 x ATR, 12+ bars apart, before the break
    const breaks: any[] = []; F.forEach((f) => (f.broke ?? []).forEach((u: number) => { const l = f.lv.find((x: any) => x.u === u); if (l) breaks.push({ ...l, f: f.f }); }));
    const j0 = sol.findIndex((b) => b.t === ts(F[0].ts));
    let rec = 0;
    for (const l of breaks) {
      const j = j0 + l.f, tol = 0.1 * F[l.f].atr; let n = 0, last = -1e9;
      for (let i = j - 150; i < j - 1; i++) { const hi = l.k === 'high', piv = hi ? sol[i]!.h > sol[i - 1]!.h && sol[i]!.h > sol[i + 1]!.h : sol[i]!.l < sol[i - 1]!.l && sol[i]!.l < sol[i + 1]!.l; if (piv && Math.abs((hi ? sol[i]!.h : sol[i]!.l) - l.p) <= tol && i - last >= 12) { n++; last = i; } }
      if (n === l.n) rec++;
    }
    L.push('## One Hour At A Time (1,147 frames, 79 retest decisions)', '',
      `- Candles match Binance SOLUSDT H1 on ${pct(F.length - mism, F.length)} frames.`,
      `- The page's \`far\` (the space measure behind its Box rule) equals the excursion over bars b+1..f, which INCLUDES the decision bar, on ${pct(withBar, dec.length)} decisions; using bars strictly before the decision bar it matches ${pct(priorOnly, dec.length)}. The page says the decision bar never enters a term; \`far\` does.`,
      `- Decision bars that close back through the level: ${pct(closedThrough, dec.length)}.`,
      `- Touch rule recovered from the data: 3-bar swing points of the level's kind within 0.10 x ATR, 12+ bars apart, in the 150 bars before the break reproduces the page's count exactly on ${pct(rec, breaks.length)} breaks (kev preset \`one-hour-spec\`).`, '');
  }
  const out = L.join('\n');
  writeFileSync(`${BRAIN}experiments/user-pages-audit.md`, out);
  log('audit-pages regenerated experiments/user-pages-audit.md');
  return out;
}
void H;
